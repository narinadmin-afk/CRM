/* ชุดกฎที่ใช้จริงต่อภาษา (สร้างครั้งเดียวตอนโหลด) */
const I18N_RULES_EN_FULL = I18N_RULES;
const I18N_RULES_ZH_FULL = I18N_RULES_ZH.concat(I18N_RULES);
const I18N_PARTS_EN_FULL = I18N_PARTS;
const I18N_PARTS_ZH_FULL = I18N_PARTS_ZH.concat(I18N_PARTS);

/** คลังข้อความของภาษาที่กำหนด (zh มี fallback เป็น en) */
function i18nMap(lang) {
  return lang === "zh" ? I18N_ZH : I18N_EN;
}

/** ภาษาปัจจุบันของแอป (เก็บที่ cmr_lang ร่วมกับหน้า login) */
function curLang() {
  const s = (typeof localStorage !== "undefined" && localStorage.getItem("cmr_lang")) || "th";
  return s === "en" || s === "zh" ? s : "th";
}

/** locale สำหรับจัดรูปแบบตัวเลข/วันที่ */
function i18nLocale() {
  const l = curLang();
  if (l === "zh") return "zh-CN";
  return l === "th" ? "th-TH" : "en-US";
}

/**
 * แปลข้อความไทยเป็นภาษาปัจจุบัน
 * ภาษาไทย → คืนข้อความเดิม | ไม่พบในคลัง → คืนข้อความเดิม (zh ใช้ en เป็น fallback)
 */
function T(s) {
  if (s === null || s === undefined) return s;
  const str = String(s);
  const lang = curLang();
  if (lang === "th") return str;
  const zh = lang === "zh";
  /* 1) คลังตรงภาษา → 2) fallback คลังอังกฤษ (สำหรับ zh) → 3) กฎข้อความเต็ม → 4) กฎชิ้นส่วน */
  const exact = i18nMap(lang)[str] || (zh ? I18N_EN[str] : "");
  if (exact) return exact;
  const rules = zh ? I18N_RULES_ZH_FULL : I18N_RULES_EN_FULL;
  for (const [re, rep] of rules) {
    const out = str.replace(re, rep);
    if (out !== str) return out;
  }
  const parts = zh ? I18N_PARTS_ZH_FULL : I18N_PARTS_EN_FULL;
  let out = str;
  for (const [re, rep] of parts) out = out.replace(re, rep);
  return out;
}

/* ---------- แปล DOM (เก็บข้อความต้นฉบับไว้เพื่อสลับกลับได้) ---------- */
const I18N_TEXT_ORIG = new WeakMap();
const I18N_ATTR_ORIG = new WeakMap();
const I18N_ATTRS = ["placeholder", "title", "aria-label", "alt"];
const I18N_SKIP_TAGS = new Set(["SCRIPT", "STYLE", "NOSCRIPT"]);

function translateDOM(root) {
  if (!root || !root.nodeType) return;
  const lang = curLang();

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const p = node.parentElement;
      if (!p || I18N_SKIP_TAGS.has(p.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  let n;
  while ((n = walker.nextNode())) nodes.push(n);
  for (const node of nodes) {
    let orig = I18N_TEXT_ORIG.get(node);
    if (orig === undefined) { orig = node.data; I18N_TEXT_ORIG.set(node, orig); }
    if (!orig.trim()) continue;
    /* แปลเฉพาะเนื้อหา — เก็บ whitespace ต้น/ท้ายไว้เหมือนเดิม */
    const mm = orig.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const lead = mm[1], core = mm[2], trail = mm[3];
    const holder = node.parentElement && node.parentElement.closest("[data-t]");
    const key = holder && holder.getAttribute("data-t");
    const outCore = (lang !== "th" && key && (i18nMap(lang)[key] || I18N_EN[key])) || T(core);
    const out = lead + outCore + trail;
    if (node.data !== out) node.data = out;
  }

  const sel = I18N_ATTRS.map((a) => "[" + a + "]").join(",");
  let els = [];
  try { els = root.querySelectorAll ? root.querySelectorAll(sel) : []; } catch (e) { els = []; }
  for (const el of els) {
    let store = I18N_ATTR_ORIG.get(el);
    if (!store) {
      store = {};
      for (const a of I18N_ATTRS) if (el.hasAttribute(a)) store[a] = el.getAttribute(a);
      I18N_ATTR_ORIG.set(el, store);
    }
    for (const a in store) {
      const out = T(store[a]);
      if (el.getAttribute(a) !== out) el.setAttribute(a, out);
    }
  }
}
